#!/usr/bin/env python3
"""Create GA4Ro-like reference closed-loop summary tables with smoothness metrics."""

from __future__ import annotations

import argparse
import csv
import shutil
from pathlib import Path

from summarize_closed_loop_cycles import summarize_cycles


SMOOTHNESS_COLUMNS = [
    "cycles_file",
    "dt_estimate_s",
    "velocity_rmse",
    "accel_rms_norm",
    "accel_energy_mean",
    "cmd_accel_rms_norm",
    "cmd_accel_energy_mean",
    "plant_accel_rms_norm",
    "plant_accel_energy_mean",
    "jerk_rms_norm_from_dq",
    "jerk_rms_norm_from_q",
    "torque_rate_rms_norm",
    "effort_rate_rms_norm",
]

DISPLAY_BY_ROBOT = {
    "ur": "UR10",
    "leap_left": "Leap Hand",
    "stanford_tidybot": "TidyBot",
}

DISPLAY_BY_BACKEND = {
    "tetrapga": "GA",
    "pinocchio": "Pinocchio",
    "casadi": "CasADi",
}


def read_first(path: Path) -> tuple[list[str], dict[str, str]]:
    with path.open(newline="") as handle:
        reader = csv.DictReader(handle)
        row = next(reader, None)
        if row is None or reader.fieldnames is None:
            raise ValueError(f"{path} has no summary row")
        return list(reader.fieldnames), row


def case_from_summary_path(path: Path) -> str:
    return path.name.removesuffix("_summary.csv")


def build_rows(batch_root: Path) -> tuple[list[str], list[dict[str, str]]]:
    summary_paths = sorted(batch_root.glob("reference_*_summary.csv"))
    if not summary_paths:
        raise SystemExit(f"No reference_*_summary.csv files found under {batch_root}")

    fieldnames: list[str] | None = None
    rows: list[dict[str, str]] = []
    for summary_path in summary_paths:
        summary_fields, summary = read_first(summary_path)
        case_name = case_from_summary_path(summary_path)
        cycles_path = summary_path.with_name(f"{case_name}_cycles.csv")
        if not cycles_path.exists():
            raise SystemExit(f"Missing cycles CSV for {case_name}: {cycles_path}")
        metrics = summarize_cycles(cycles_path)

        row = {
            "case_name": case_name,
            "summary_file": summary_path.name,
            **summary,
        }
        for column in SMOOTHNESS_COLUMNS:
            row[column] = metrics.get(column, "")
        row["robot_display"] = DISPLAY_BY_ROBOT.get(row.get("robot", ""), row.get("robot", ""))
        row["backend_display"] = DISPLAY_BY_BACKEND.get(row.get("backend", ""), row.get("backend", ""))

        if fieldnames is None:
            fieldnames = ["case_name", "summary_file"] + summary_fields + SMOOTHNESS_COLUMNS
            fieldnames += ["robot_display", "backend_display"]
        rows.append(row)

    if fieldnames is None:
        raise SystemExit(f"No valid summaries found under {batch_root}")
    return fieldnames, rows


def write_csv(path: Path, fieldnames: list[str], rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_summary_md(output_dir: Path, batch_root: Path, rows: list[dict[str, str]]) -> None:
    robots = ", ".join(sorted({row["robot"] for row in rows}))
    backends = ", ".join(sorted({row["backend"] for row in rows}))
    durations = ", ".join(sorted({row["experiment_duration_s"] for row in rows}))
    text = f"""# Closed-Loop MPC Reference Metrics

Status: generated by `scripts/run_reference_closed_loop_metrics.sh`.

Configuration:

- Simulator: MuJoCo through `ga_ocp_ros2/scripts/joint_command_executor.py`.
- Controller: GA-OCP closed-loop receding-horizon nominal-model MPC.
- Cases: no plant perturbation, sinusoidal reference tracking.
- Running OCP cost includes state tracking, control effort, soft velocity limits, and acceleration regularization.
- Solver uses box-FDDP with hard control bounds from each robot's effort limits.
- Robots: {robots}.
- Backends: {backends}.
- Duration per case: {durations} s.
- Viewer enabled during this run: false.

Outputs:

- `{batch_root.relative_to(output_dir)}/combined_summary.csv`: GA4Ro-like per-case summary.
- `mujoco_closed_loop_metrics_summary.csv`: stable combined summary with jerk/smoothness columns.
- `mujoco_closed_loop_metrics_with_conditions.csv`: same rows plus robot/backend display labels.
- `{batch_root.relative_to(output_dir)}/*_cycles.csv`: raw closed-loop cycle logs.

Smoothness metrics:

- `accel_rms_norm` is the primary smoothness metric, computed from the planned first-step acceleration `ddq_cmd` when available.
- `plant_accel_rms_norm` is retained as a plant-velocity finite-difference diagnostic.
"""
    (output_dir / "summary.md").write_text(text)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--batch-root", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()

    fieldnames, rows = build_rows(args.batch_root)

    combined = args.batch_root / "combined_summary.csv"
    write_csv(combined, fieldnames, rows)

    stable_summary = args.output_dir / "mujoco_closed_loop_metrics_summary.csv"
    write_csv(stable_summary, fieldnames, rows)

    with_conditions = args.output_dir / "mujoco_closed_loop_metrics_with_conditions.csv"
    write_csv(with_conditions, fieldnames, rows)

    shutil.copyfile(combined, args.output_dir / "mujoco_closed_loop_reference_combined_summary.csv")
    write_summary_md(args.output_dir, args.batch_root, rows)

    print(combined)
    print(stable_summary)
    print(with_conditions)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
